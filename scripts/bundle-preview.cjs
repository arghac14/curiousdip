// Classic scripts load from file:// without fetching JSON or requiring a server.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const read = file => JSON.parse(fs.readFileSync(path.join(root, 'data', file), 'utf8'));
const presets = require('./presets.cjs')(root);
fs.writeFileSync(path.join(root, 'data/presets.json'),JSON.stringify(presets,null,2)+'\n');
const payload = {profile:read('profile.json'),photoseries:read('photoseries.json'),blog:read('blog.json'),videos:read('videos.json'),presets,seo:read('seo.json')};
fs.writeFileSync(path.join(root, 'data/preview-data.js'), '// Generated by npm run photos. Edit source JSON, then regenerate.\nwindow.CURIOUSDIP_PREVIEW = ' + JSON.stringify(payload).replace(/</g, '\\u003c') + ';\n');
console.log('Direct-file preview data refreshed.');
